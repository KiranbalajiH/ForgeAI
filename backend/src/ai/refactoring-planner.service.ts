/** Normalize focusArea string to canonical key */
function normalizeFocusArea(focusArea?: string): string {
  if (!focusArea) return "General";
  const norm = focusArea.trim().toLowerCase().replace(/[-_]/g, " ");

  if (norm.includes("arch")) return "Architecture";
  if (norm.includes("perf")) return "Performance";
  if (norm.includes("maintain")) return "Maintainability";
  if (norm.includes("sec")) return "Security";
  if (norm.includes("quality")) return "Code Quality";
  if (norm.includes("general")) return "General";

  return focusArea.trim();
}

/** Extract overall priority from LLM response */
function extractOverallPriority(markdown: string): RefactoringPriority {
  if (/Overall\s*Priority:\s*High/i.test(markdown) || (markdown.match(/Priority:\s*High/gi) || []).length > 1) {
    return "High";
  }
  if (/Overall\s*Priority:\s*Low/i.test(markdown)) {
    return "Low";
  }
  return "Medium";
}

/** Extract key risks list from LLM response */
function extractKeyRisks(markdown: string): string[] {
  const risks: string[] = [];
  const lines = markdown.split("\n");
  let inRisks = false;
  for (const line of lines) {
    if (/^#+\s.*[Rr]isk/.test(line)) {
      inRisks = true;
      continue;
    }
    if (inRisks && /^#+\s/.test(line)) {
      break;
    }
    if (inRisks) {
      const match = line.match(/^\s*[-*]\s+(.+)/) || line.match(/^\s*\d+\.\s+(.+)/);
      if (match) {
        risks.push(match[1].trim());
      }
    }
  }
  return risks.length > 0 ? risks : [
    "Potential regression in un-tested execution paths",
    "Requires thorough integration testing before deployment"
  ];
}

/** Extract recommended step order from LLM response */
function extractStepOrder(markdown: string): string[] {
  const steps: string[] = [];
  const lines = markdown.split("\n");
  let inSteps = false;
  for (const line of lines) {
    if (/^#+\s.*(Recommended Order|Step Order|Phases|Roadmap)/i.test(line)) {
      inSteps = true;
      continue;
    }
    if (inSteps && /^#+\s/.test(line)) {
      break;
    }
    if (inSteps) {
      const match = line.match(/^\s*\d+\.\s+(.+)/) || line.match(/^\s*[-*]\s+(.+)/);
      if (match) {
        steps.push(match[1].trim());
      }
    }
  }
  return steps.length > 0
    ? steps
    : ["Phase 1: High-Priority Hardening", "Phase 2: Architectural Refactoring", "Phase 3: Code Cleanup & Testing"];
}

/**
 * RefactoringPlannerService
 *
 * Responsibility:
 *  1. Accept repository and optional focusArea.
 *  2. Reuse WorkspaceAnalysisService to retrieve baseline repository health & complexity.
 *  3. Perform targeted context retrieval via RepositoryKnowledgeService.
 *  4. Construct a focus-area specific LLM prompt for refactoring planning.
 *  5. Call LLMService and format the response into a structured RefactoringPlanResult model.
 */
export class RefactoringPlannerService extends AIServiceBase {
  private workspaceService: WorkspaceAnalysisService;
  private knowledgeService: RepositoryKnowledgeService;
  private llmService: LLMService;

  constructor(
    workspaceService?: WorkspaceAnalysisService,
    knowledgeService?: RepositoryKnowledgeService,
    llmService?: LLMService,
    configService?: AIConfigService
  ) {
    super("RefactoringPlannerService", configService);
    this.knowledgeService = knowledgeService ?? new RepositoryKnowledgeService(undefined, undefined, undefined, undefined, configService);
    this.workspaceService = workspaceService ?? new WorkspaceAnalysisService(this.knowledgeService, undefined, llmService, configService);
    this.llmService = llmService ?? new LLMService(undefined, configService);
  }

  /**
   * Generates a structured Refactoring Plan for a repository and focus area.
   *
   * @param repository - Repository name / slug
   * @param focusArea  - Optional focus area ("Architecture", "Performance", "Maintainability", "Security", "Code Quality", "General")
   * @param options    - Optional retrieval parameters
   */
  async plan(
    repository: string,
    focusArea?: FocusArea,
    options?: KnowledgeRetrievalOptions
  ): Promise<RefactoringPlanResult> {
    return this.execute(repository, async (context) => {
        const canonicalFocus = normalizeFocusArea(focusArea);

    // 1. Reuse WorkspaceAnalysisService to get baseline repository analysis
    const workspaceAnalysis: WorkspaceAnalysis = await this.workspaceService.analyze(
      repository,
      options
    );

    // 2. Select focus area config
    const config = FOCUS_AREA_CONFIGS[canonicalFocus] ?? FOCUS_AREA_CONFIGS["General"];

    // 3. Perform targeted retrieval via RepositoryKnowledgeService
    const knowledgeResult: RepositoryKnowledgeResult = this.knowledgeService.retrieve(
      repository,
      config.retrievalQuery,
      options
    );

    // 4. Format workspace summary for LLM context
    const workspaceSummary = `
## Repository Overview & Health Summary
- **Repository:** ${workspaceAnalysis.repository}
- **Language:** ${workspaceAnalysis.technologies.language}
- **Framework:** ${workspaceAnalysis.technologies.framework}
- **Database:** ${workspaceAnalysis.technologies.database} (${workspaceAnalysis.technologies.orm})
- **Total Files:** ${workspaceAnalysis.totalFiles}
- **Estimated Complexity:** ${workspaceAnalysis.estimatedComplexity}
- **Major Modules:** ${workspaceAnalysis.majorModules.join(", ") || "None"}
- **Entry Points:** ${workspaceAnalysis.entryPoints.join(", ") || "None"}
- **Initial Recommendations:**
${workspaceAnalysis.aiRecommendations}
`;

    // 5. Build refactoring plan prompt
    const planPrompt = [
      `You are a Senior Software Architect creating a structured, action-oriented Refactoring Plan for "${repository}".`,
      `Focus Area: **${canonicalFocus}**`,
      ``,
      `Your refactoring plan MUST be structured with the following exact Markdown headers:`,
      ``,
      `# Refactoring Plan: ${repository} (${canonicalFocus})`,
      ``,
      `## Executive Summary`,
      `Provide a high-level summary of the refactoring strategy, major debt identified, and expected business/technical outcome.`,
      ``,
      `## Overall Assessment`,
      `- **Overall Priority:** High | Medium | Low`,
      `- **Estimated Impact:** High | Medium | Low`,
      `- **Estimated Effort:** Small | Medium | Large`,
      ``,
      `## Refactoring Opportunities`,
      `List 3 to 6 concrete refactoring tasks. For each task use this format:`,
      `### [Order Number]. [Task Title]`,
      `- **Priority:** High | Medium | Low`,
      `- **Estimated Impact:** High | Medium | Low`,
      `- **Estimated Effort:** Small | Medium | Large`,
      `- **Description:** Explanation of the refactoring task.`,
      `- **Risks:** Potential risks or regressions.`,
      ``,
      `## Recommended Step Order`,
      `Numbered list of phases or steps in order of execution.`,
      ``,
      `## Key Risks & Mitigation`,
      `Bullet list of overall risks and mitigation strategies.`,
      ``,
      `---`,
      ``,
      workspaceSummary,
      ``,
      `---`,
      ``,
      knowledgeResult.prompt,
    ].join("\n");

    // 6. Call LLMService to generate the refactoring plan
    const markdownPlan = await this.trackLLM(context, planPrompt, () =>
      this.llmService.chat(planPrompt)
    );

    // 7. Parse structured metrics from markdown output
    const overallPriority = extractOverallPriority(markdownPlan);
    const keyRisks = extractKeyRisks(markdownPlan);
    const recommendedStepOrder = extractStepOrder(markdownPlan);

    // Extract executive summary (text under "## Executive Summary")
    const execMatch = markdownPlan.match(/##\s+Executive Summary\s*\n+([\s\S]+?)(?=\n##|\n#|$)/);
    const executiveSummary = execMatch
      ? execMatch[1].trim()
      : `Refactoring plan focused on ${canonicalFocus} for ${repository}.`;

    return {
      executiveSummary,
      opportunities: [],      // Full details included in markdownPlan
      overallPriority,
      overallEstimatedImpact: "High",
      overallEstimatedEffort: workspaceAnalysis.estimatedComplexity === "High" || workspaceAnalysis.estimatedComplexity === "Very High" ? "Large" : "Medium",
      recommendedStepOrder,
      keyRisks,
      markdownPlan,
      sources: knowledgeResult.sources,
      metadata: this.buildMetadata(repository, knowledgeResult, { focusArea: canonicalFocus, complexity: workspaceAnalysis.estimatedComplexity }) as any,
      stats: knowledgeResult.stats,
    };
    }, {
      category: "AIResponses",
      payload: { focusArea, options },
    });
  }
}
