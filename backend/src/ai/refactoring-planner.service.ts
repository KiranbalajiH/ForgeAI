export type FocusArea =
  | "Architecture"
  | "Performance"
  | "Maintainability"
  | "Security"
  | "Code Quality"
  | "General"
  | string;

export type RefactoringPriority = "High" | "Medium" | "Low";
export type RefactoringImpact = "High" | "Medium" | "Low";
export type RefactoringEffort = "Small" | "Medium" | "Large";

export interface RefactoringOpportunity {
  /** Title of the refactoring task */
  title: string;
  /** Detailed description of the opportunity */
  description: string;
  /** Priority level */
  priority: RefactoringPriority;
  /** Estimated impact on code quality/performance */
  estimatedImpact: RefactoringImpact;
  /** Estimated effort required */
  estimatedEffort: RefactoringEffort;
  /** Recommended execution step order (1-indexed) */
  recommendedOrder: number;
  /** Potential risks associated with this refactoring step */
  risks: string[];
  /** Affected source files (if identifiable) */
  affectedFiles?: string[];
}

export interface RefactoringPlanResult {
  /** Executive summary of the refactoring strategy */
  executiveSummary: string;
  /** List of structured refactoring opportunities */
  opportunities: RefactoringOpportunity[];
  /** Overall priority of the plan */
  overallPriority: RefactoringPriority;
  /** Overall estimated impact */
  overallEstimatedImpact: string;
  /** Overall estimated effort */
  overallEstimatedEffort: string;
  /** Sequential step order summary */
  recommendedStepOrder: string[];
  /** Consolidated key risks across all steps */
  keyRisks: string[];
  /** Full raw markdown refactoring plan generated by the LLM */
  markdownPlan: string;
  /** Citable source references */
  sources: SourceReference[];
  /** Planning metadata */
  metadata: {
    repository: string;
    focusArea: string;
    complexity: string;
    intent: string;
    contextDomainsUsed: ContextDomain[];
    strategy: string;
  };
  /** Retrieval and execution statistics */
  stats: KnowledgeRetrievalStats;
}

